describe("parseDirective — row", () => {
  it("parses row directive with columns", () => {
    const d = parseDirective(
      "row\n  Name: string; required\n  Age: string; optional",
    );
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(d.columns["Name"]).toMatchObject({ required: true });
      expect(d.columns["Age"]).toMatchObject({ required: false });
    }
  });

  it("parses min-rows modifier on opener", () => {
    const d = parseDirective("row; min-rows: 2\nName: string; required");
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(d.minRows).toBe(2);
    }
  });

  it("parses enum column type", () => {
    const d = parseDirective(
      "row\n  Status: enum: Active | Inactive; required",
    );
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(d.columns["Status"]).toMatchObject({
        enumChoices: ["Active", "Inactive"],
      });
    }
  });

  it("strips surrounding quotes from column names", () => {
    const d = parseDirective('row\n  "#": string; required');
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(d.columns["#"]).toMatchObject({ required: true });
      expect(d.columns['"#"']).toBeUndefined();
    }
  });

  it("strips single quotes from column names", () => {
    const d = parseDirective("row\n  'name': string; required");
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(d.columns["name"]).toMatchObject({ required: true });
    }
  });
});

