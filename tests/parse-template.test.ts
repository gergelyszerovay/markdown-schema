describe("parseDirective — // prose comments in field directive", () => {
  it("ignores trailing // prose line", () => {
    const d = parseDirective(
      "string; required\n// Write a concise one-sentence highlight.",
    );
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.required).toBe(true);
    }
  });

  it("ignores multiple // prose lines", () => {
    const d = parseDirective(
      "string; optional\n// Keep it under 80 chars.\n// Use present tense.",
    );
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.required).toBe(false);
    }
  });

  it("extra non-// line after spec is silently treated as unknown modifier", () => {
    const d = parseDirective("string; required\nsome extra directive line");
    expect(d.kind).toBe("field");
  });
});

describe("parseDirective — // prose comments in enum directive", () => {
  it("ignores trailing // prose line", () => {
    const d = parseDirective(
      "enum: Alpha | Beta | GA\n// Choose the release stage.",
    );
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") {
      expect(d.choices).toEqual(["Alpha", "Beta", "GA"]);
    }
  });
});

describe("parseDirective — // prose comments in row directive", () => {
  it("ignores interleaved // prose lines", () => {
    const d = parseDirective(
      "row; min-rows: 1\n// Each row is one criterion.\nID: string; required\nDescription: string; required",
    );
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(Object.keys(d.columns)).toEqual(["ID", "Description"]);
      expect(d.minRows).toBe(1);
    }
  });

  it("does not treat a // line containing : as a column definition", () => {
    const d = parseDirective(
      "row\n// Note: fill all required fields\nName: string; required",
    );
    expect(d.kind).toBe("row");
    if (d.kind === "row") {
      expect(Object.keys(d.columns)).toEqual(["Name"]);
      expect(d.columns["// Note"]).toBeUndefined();
    }
  });
});

describe("parseDirective — // prose comments in section directive", () => {
  it("ignores // prose lines in section body (modifiers must be on opener)", () => {
    const d = parseDirective(
      "section; optional; remove-if Type=View\n// This section may be omitted for View components.",
    );
    expect(d.kind).toBe("section");
    if (d.kind === "section") {
      expect(d.optional).toBe(true);
      expect(d.removeIf).toEqual({ key: "Type", value: "View" });
    }
  });
});

