describe("extractDirectiveBody", () => {
  it("extracts body from TEMPLATE-ONLY comment", () => {
    expect(extractDirectiveBody("<!-- TEMPLATE-ONLY: enum: A | B -->")).toBe(
      "enum: A | B",
    );
  });

  it("returns null for non-TEMPLATE-ONLY comments", () => {
    expect(extractDirectiveBody("<!-- regular comment -->")).toBeNull();
  });

  it("handles multiline bodies", () => {
    const body = extractDirectiveBody(
      "<!-- TEMPLATE-ONLY: section\n  optional\n-->",
    );
    expect(body).toContain("section");
    expect(body).toContain("optional");
  });
});

