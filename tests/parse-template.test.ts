describe("parseDirective — freetext", () => {
  it("parses bare freetext directive", () => {
    const d = parseDirective("freetext");
    expect(d.kind).toBe("freetext");
    if (d.kind === "freetext") {
      expect(d.optional).toBe(false);
    }
  });

  it("parses freetext; optional", () => {
    const d = parseDirective("freetext; optional");
    expect(d.kind).toBe("freetext");
    if (d.kind === "freetext") {
      expect(d.optional).toBe(true);
    }
  });

  it("parses freetext; required as optional=false", () => {
    const d = parseDirective("freetext; required");
    expect(d.kind).toBe("freetext");
    if (d.kind === "freetext") {
      expect(d.optional).toBe(false);
    }
  });

  it("throws DirectiveError for unknown freetext modifier", () => {
    expect(() => parseDirective("freetext; bogus")).toThrow(DirectiveError);
    expect(() => parseDirective("freetext; bogus")).toThrow(
      /unknown freetext modifier/,
    );
  });

  it("throws DirectiveError when body contains non-// non-blank line", () => {
    expect(() => parseDirective("freetext\nnot a comment line")).toThrow(
      DirectiveError,
    );
    expect(() => parseDirective("freetext\nnot a comment line")).toThrow(
      /freetext modifiers must be on the directive opener/,
    );
  });
});

