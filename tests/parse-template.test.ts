describe("parseTemplate — table-row template", () => {
  const templateRaw = [
    "# Feature Spec",
    "",
    "## 1. Acceptance Criteria",
    "",
    "| ID | Description | Priority |",
    "| -- | ----------- | -------- |",
    "<!-- TEMPLATE-ONLY: row; min-rows: 1",
    "ID: string; regex `^AC-\\d+$`; required",
    "Description: string; required",
    "Priority: enum: Low | Medium | High; required",
    "-->",
    "| AC-001 | Sample. | High |",
  ].join("\n");
  const schema = parseTemplate(templateRaw);

  it("accepts valid table row", () => {
    const raw =
      "# Feature Spec\n\n## 1. Acceptance Criteria\n\n| ID | Description | Priority |\n| -- | ----------- | -------- |\n| AC-001 | First criterion. | High |\n";
    const doc = schema.parse(raw) as Record<string, unknown>;
    const rows = doc["acceptanceCriteria"] as Record<string, string>[];
    expect(rows).toHaveLength(1);
    expect(rows[0]["ID"]).toBe("AC-001");
    expect(rows[0]["Priority"]).toBe("High");
  });

  it("rejects invalid ID format", () => {
    const raw =
      "# Feature Spec\n\n## 1. Acceptance Criteria\n\n| ID | Description | Priority |\n| -- | ----------- | -------- |\n| 001 | First criterion. | High |\n";
    expect(() => schema.parse(raw)).toThrow(ZodError);
  });

  it("rejects invalid enum Priority", () => {
    const raw =
      "# Feature Spec\n\n## 1. Acceptance Criteria\n\n| ID | Description | Priority |\n| -- | ----------- | -------- |\n| AC-001 | First criterion. | Critical |\n";
    expect(() => schema.parse(raw)).toThrow(ZodError);
  });
});

describe("parseTemplate — section-optional template", () => {
  const templateRaw = [
    "# Document",
    "",
    "## 1. Summary",
    "",
    "<!-- TEMPLATE-ONLY: freetext; required -->",
    "",
    "Short description.",
    "",
    "## 2. Notes",
    "",
    "<!-- TEMPLATE-ONLY: section; optional -->",
    "",
    "| Key | Value |",
    "| --- | ----- |",
    "<!-- TEMPLATE-ONLY: row",
    "Key: string; required",
    "Value: string; required",
    "-->",
    "| key | value |",
  ].join("\n");
  const schema = parseTemplate(templateRaw);

  it("accepts document without optional section", () => {
    const raw = "# Document\n\n## 1. Summary\n\nShort description.\n";
    const doc = schema.parse(raw) as Record<string, unknown>;
    expect(doc["notes"]).toBeUndefined();
  });

  it("accepts document with optional section present", () => {
    const raw = [
      "# Document",
      "",
      "## 1. Summary",
      "",
      "Short description.",
      "",
      "## 2. Notes",
      "",
      "| Key | Value |",
      "| --- | ----- |",
      "| foo | bar |",
    ].join("\n");
    const doc = schema.parse(raw) as Record<string, unknown>;
    const notes = doc["notes"] as Record<string, string>[];
    expect(notes).toHaveLength(1);
    expect(notes[0]["Key"]).toBe("foo");
  });
});

