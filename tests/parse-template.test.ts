describe("parseDirective — field", () => {
  it("parses required string field", () => {
    const d = parseDirective("string; required");
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.required).toBe(true);
    }
  });

  it("parses optional field", () => {
    const d = parseDirective("string; optional");
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.required).toBe(false);
    }
  });

  it("parses regex field", () => {
    const d = parseDirective("string; regex `^[a-z]+$`; required");
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.regex).toBe("^[a-z]+$");
      expect(d.required).toBe(true);
    }
  });

  it("parses only-if modifier", () => {
    const d = parseDirective("string; optional; only-if Type=Primitive");
    expect(d.kind).toBe("field");
    if (d.kind === "field") {
      expect(d.onlyIf).toEqual({ key: "Type", value: "Primitive" });
    }
  });
});

