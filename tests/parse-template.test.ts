describe("parseDirective — enum", () => {
  it("parses enum directive", () => {
    const d = parseDirective("enum: A | B | C");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") {
      expect(d.choices).toEqual(["A", "B", "C"]);
    }
  });

  it("trims choice whitespace", () => {
    const d = parseDirective("enum: Root | Layout | Container");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") {
      expect(d.choices).toEqual(["Root", "Layout", "Container"]);
    }
  });

  it("strips ; required modifier from choices", () => {
    const d = parseDirective("enum: Feature | Shared; required");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") {
      expect(d.choices).toEqual(["Feature", "Shared"]);
    }
  });

  it("required=true when ; required present", () => {
    const d = parseDirective("enum: Alpha | Beta | GA; required");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") expect(d.required).toBe(true);
  });

  it("required=true when no modifier present (default)", () => {
    const d = parseDirective("enum: A | B | C");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") expect(d.required).toBe(true);
  });

  it("required=false when ; optional present", () => {
    const d = parseDirective("enum: Free | Pro; optional");
    expect(d.kind).toBe("enum");
    if (d.kind === "enum") {
      expect(d.choices).toEqual(["Free", "Pro"]);
      expect(d.required).toBe(false);
    }
  });
});

