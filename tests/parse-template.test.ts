describe("parseTemplate — enum-only template", () => {
  const templateRaw = `# Status Report\n\n## 1. Status\n\n- Level: <!-- TEMPLATE-ONLY: enum: Low | Medium | High | Critical; required -->\n`;
  const schema = parseTemplate(templateRaw);

  it("accepts valid enum value", () => {
    const doc = schema.parse(
      `# Status Report\n\n## 1. Status\n\n- Level: High\n`,
    ) as Record<string, unknown>;
    const status = doc["status"] as Record<string, string | undefined>;
    expect(status["Level"]).toBe("High");
  });

  it("rejects invalid enum value", () => {
    expect(() =>
      schema.parse(`# Status Report\n\n## 1. Status\n\n- Level: Extreme\n`),
    ).toThrow(ZodError);
  });
});

describe("parseTemplate — title with hyphen prefix (no space)", () => {
  const templateRaw = [
    "# CR-<!-- TEMPLATE-ONLY: string; required; regex `\\d{4}` -->",
    "",
    "## 1. Summary",
    "",
    "<!-- TEMPLATE-ONLY: freetext; required -->",
  ].join("\n");
  const schema = parseTemplate(templateRaw);

  it("accepts CR-0033 with no space between prefix and ID", () => {
    const raw = "# CR-0033\n\n## 1. Summary\n\nBody.\n";
    const doc = schema.parse(raw) as Record<string, unknown>;
    expect(doc["title"]).toBe("CR-0033");
  });

  it("rejects CR-12 (only 2 digits, not 4)", () => {
    const raw = "# CR-12\n\n## 1. Summary\n\nBody.\n";
    expect(() => schema.parse(raw)).toThrow(ZodError);
  });

  it("rejects CR- 0033 (extra space breaks the pattern)", () => {
    const raw = "# CR- 0033\n\n## 1. Summary\n\nBody.\n";
    expect(() => schema.parse(raw)).toThrow(ZodError);
  });
});

